"""Builds the starter threat-intelligence files in data/ti.

1. attack_seed.json: 18 MITRE ATT&CK techniques relevant to IoT, as a STIX 2.1
   bundle.  The technique IDs and names are ATT&CK's own; the descriptions are
   short summaries written for this project.  Run scripts/update_ti.py to
   replace them with MITRE's full, official descriptions (needs internet).

2. demo_indicators.json: four indicators and one campaign used by the attack
   simulator.  They are SYNTHETIC: the IP addresses come from ranges reserved
   for documentation (RFC 5737), so they can never be confused with real
   threat data.

Run:  python scripts/build_seed_ti.py
"""
import json
import uuid
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "data" / "ti"
NS = uuid.UUID("6f1d3c5e-2a7b-4c1d-9e8f-0a1b2c3d4e5f")
CREATED = "2026-10-12T00:00:00.000Z"


def sid(kind, key):
    return f"{kind}--{uuid.uuid5(NS, key)}"


TECHNIQUES = [
    ("T1110", "Brute Force", ["credential-access"],
     "Adversaries may use brute force to gain access to accounts when passwords are unknown, systematically "
     "guessing passwords. On IoT devices this appears as many repeated failed authentication or login attempts "
     "against a device service such as Telnet, SSH or a web interface, often from a single external address."),
    ("T1078", "Valid Accounts", ["initial-access", "persistence", "defense-evasion"],
     "Adversaries may obtain and abuse the credentials of existing accounts, including default credentials on "
     "devices, to gain access. A successful login from an unusual source after credentials were obtained."),
    ("T1601", "Modify System Image", ["defense-evasion"],
     "Adversaries may make changes to the operating system or firmware image of embedded network devices to "
     "weaken defenses or add capabilities. Evidence includes a firmware version or firmware hash that does not "
     "match the known-good image for that device."),
    ("T1495", "Firmware Corruption", ["impact"],
     "Adversaries may overwrite or corrupt the firmware of devices to render them inoperable or unable to boot, "
     "causing a loss of availability of the device."),
    ("T1499", "Endpoint Denial of Service", ["impact"],
     "Adversaries may degrade or block the availability of a system by exhausting its resources, such as CPU, "
     "memory and running processes, or by flooding a service. The host becomes saturated and unresponsive."),
    ("T1496", "Resource Hijacking", ["impact"],
     "Adversaries may use the compute resources of compromised systems for their own resource-intensive tasks, "
     "such as cryptocurrency mining, running unexpected jobs that consume processor and energy."),
    ("T1021", "Remote Services", ["lateral-movement"],
     "Adversaries may use remote services to log into and move laterally between systems in a network, "
     "reaching hosts and nodes that the compromised system does not normally communicate with."),
    ("T1570", "Lateral Tool Transfer", ["lateral-movement"],
     "Adversaries may transfer tools or other files between systems in a compromised environment to spread "
     "their capability from one host to another."),
    ("T1557", "Adversary-in-the-Middle", ["credential-access", "collection"],
     "Adversaries may position themselves between networked devices, for example through ARP cache poisoning, "
     "spoofed addresses or forged frames, to intercept or alter traffic and protocol translations."),
    ("T1040", "Network Sniffing", ["credential-access", "discovery"],
     "Adversaries may passively capture network traffic to collect information such as credentials or "
     "configuration details sent across the network."),
    ("T1595", "Active Scanning", ["reconnaissance"],
     "Adversaries may execute active scans against victim infrastructure, probing IP blocks and many ports "
     "with scanning traffic to discover exposed hosts and services before an attack."),
    ("T1046", "Network Service Discovery", ["discovery"],
     "Adversaries may attempt to list the services running on remote hosts, typically with port scans and "
     "vulnerability scans that send probes such as TCP SYN packets to many ports."),
    ("T1498", "Network Denial of Service", ["impact"],
     "Adversaries may perform network denial of service by flooding the target's bandwidth with a high volume "
     "of packets, for example UDP, ICMP or TCP SYN floods, frequently generated by a botnet of compromised "
     "devices sending to many destinations."),
    ("T1190", "Exploit Public-Facing Application", ["initial-access"],
     "Adversaries may exploit a weakness in an internet-facing application or web interface, for example with "
     "SQL injection or command injection, to gain initial access."),
    ("T1071", "Application Layer Protocol", ["command-and-control"],
     "Adversaries may communicate with compromised systems using application layer protocols to blend in with "
     "normal traffic, with devices regularly contacting a command and control server."),
    ("T1584.005", "Compromise Infrastructure: Botnet", ["resource-development"],
     "Adversaries may compromise numerous third-party systems, including IoT devices, to form a botnet that they "
     "can then direct, for example to launch large-scale denial of service."),
    ("T1562", "Impair Defenses", ["defense-evasion"],
     "Adversaries may disable or modify security tools and logging to avoid detection."),
    ("T1005", "Data from Local System", ["collection"],
     "Adversaries may search local system sources, such as files and databases, to find data of interest before "
     "exfiltration."),
]

INDICATORS = [
    ("203.0.113.45", "Credential-guessing source (demo)", "T1110",
     "Synthetic demo indicator: address observed guessing device passwords."),
    ("203.0.113.66", "Botnet command and control server (demo)", "T1498",
     "Synthetic demo indicator: command and control server directing IoT botnet floods."),
    ("198.51.100.23", "Frame spoofing source (demo)", "T1557",
     "Synthetic demo indicator: address injecting spoofed frames to intercept IoT traffic."),
    ("203.0.113.77", "Scanning host (demo)", "T1595",
     "Synthetic demo indicator: host performing port scans against IoT gateways."),
]


def build():
    OUT.mkdir(parents=True, exist_ok=True)
    objs = []
    for tid, name, tactics, desc in TECHNIQUES:
        objs.append({
            "type": "attack-pattern", "spec_version": "2.1", "id": sid("attack-pattern", tid),
            "created": CREATED, "modified": CREATED, "name": name, "description": desc,
            "kill_chain_phases": [{"kill_chain_name": "mitre-attack", "phase_name": t} for t in tactics],
            "external_references": [{"source_name": "mitre-attack", "external_id": tid,
                                     "url": f"https://attack.mitre.org/techniques/{tid.replace('.', '/')}/"}],
            "x_afddt_note": "Summary written for the AFDDT starter set; run scripts/update_ti.py for MITRE's text.",
        })
    (OUT / "attack_seed.json").write_text(json.dumps(
        {"type": "bundle", "id": sid("bundle", "attack_seed"), "objects": objs}, indent=1), encoding="utf-8")

    objs = []
    camp = sid("campaign", "demo")
    objs.append({"type": "campaign", "spec_version": "2.1", "id": camp, "created": CREATED, "modified": CREATED,
                 "name": "Demo IoT botnet campaign (synthetic)",
                 "description": "Synthetic campaign used by the AFDDT attack simulator: credential guessing against "
                                "cameras, lateral movement, then botnet flooding."})
    for ip, name, tid, desc in INDICATORS:
        iid = sid("indicator", ip)
        objs.append({"type": "indicator", "spec_version": "2.1", "id": iid, "created": CREATED, "modified": CREATED,
                     "name": name, "description": desc, "pattern": f"[ipv4-addr:value = '{ip}']",
                     "pattern_type": "stix", "valid_from": CREATED, "labels": ["demo", "synthetic"]})
        objs.append({"type": "relationship", "spec_version": "2.1", "id": sid("relationship", ip + tid),
                     "created": CREATED, "modified": CREATED, "relationship_type": "indicates",
                     "source_ref": iid, "target_ref": sid("attack-pattern", tid)})
        objs.append({"type": "relationship", "spec_version": "2.1", "id": sid("relationship", ip + "camp"),
                     "created": CREATED, "modified": CREATED, "relationship_type": "attributed-to",
                     "source_ref": iid, "target_ref": camp})
    (OUT / "demo_indicators.json").write_text(json.dumps(
        {"type": "bundle", "id": sid("bundle", "demo"), "objects": objs}, indent=1), encoding="utf-8")
    print(f"wrote {OUT / 'attack_seed.json'} and {OUT / 'demo_indicators.json'}")


if __name__ == "__main__":
    build()
